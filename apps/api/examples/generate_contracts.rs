use api::{
    domain::{
        city::entity::City, contributor::entity::Contributor, lettering::entity::LocationSource,
    },
    infrastructure::monitoring::{HttpMetric, HttpMetricsSnapshot},
    presentation::http::{
        contracts::*,
        handlers::{admin::*, admin_comments::*, auth::*, me::*},
    },
};
use std::{error::Error, path::PathBuf};
use ts_rs::TS;

fn main() -> Result<(), Box<dyn Error>> {
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../packages/types/src/generated/contracts.ts");
    let config = ts_rs::Config::default();
    let declarations = [
        HttpMetric::decl(&config),
        HttpMetricsSnapshot::decl(&config),
        PublicCoordinates::decl(&config),
        PublicThumbnailUrls::decl(&config),
        PublicImageMetadata::decl(&config),
        LocationSource::decl(&config),
        PublicLetteringStatus::decl(&config),
        PublicLettering::decl(&config),
        LetteringDetailResponse::decl(&config),
        GalleryResponse::decl(&config),
        PublicComment::decl(&config),
        City::decl(&config),
        Contributor::decl(&config),
        AuthUser::decl(&config),
        AuthResponse::decl(&config),
        MyUploadItem::decl(&config),
        MyUploadsResponse::decl(&config),
        MyUploadStatusHistoryItem::decl(&config),
        MyUploadMetadataHistoryItem::decl(&config),
        MyUploadTimelineResponse::decl(&config),
        NotificationItem::decl(&config),
        NotificationsResponse::decl(&config),
        ModerationItem::decl(&config),
        ModerationQueueResponse::decl(&config),
        AdminAuditLogItem::decl(&config),
        AdminAuditLogsResponse::decl(&config),
        StatsResponse::decl(&config),
        BulkActionFailure::decl(&config),
        BulkActionResponse::decl(&config),
        AdminCommentItem::decl(&config),
        AdminCommentsResponse::decl(&config),
        BulkCommentActionFailure::decl(&config),
        BulkCommentActionResponse::decl(&config),
    ];
    let output = format!(
        "// Generated by cargo run --locked --example generate_contracts. Do not edit.\n\n{}\n",
        declarations
            .iter()
            .map(|decl| format!("export {decl}"))
            .collect::<Vec<_>>()
            .join("\n\n")
    );
    if std::env::args().any(|arg| arg == "--check") {
        if std::fs::read_to_string(&path)? != output {
            return Err("API contracts drifted. Run cargo run --locked --example generate_contracts and commit the output.".into());
        }
        println!("API contracts match the Rust response allowlists");
    } else {
        std::fs::write(&path, output)?;
    }
    Ok(())
}
